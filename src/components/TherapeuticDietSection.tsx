export const TherapeuticDietSection: React.FC = () => {
  const [selectedPlan, setSelectedPlan] = useState<DietPlan>(DIET_PLANS[0]);
  const [searchQuery, setSearchQuery] = useState<string>('');
  const [isDropdownOpen, setIsDropdownOpen] = useState<boolean>(false);
  const [isLoadingCustom, setIsLoadingCustom] = useState<boolean>(false);
  const [customError, setCustomError] = useState<string>('');
  const [copied, setCopied] = useState<boolean>(false);

  const dropdownRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  useEffect(() => {
    const handleOutside = (e: MouseEvent | TouchEvent) => {
      if (dropdownRef.current && !dropdownRef.current.contains(e.target as Node)) {
        setIsDropdownOpen(false);
      }
    };
    document.addEventListener('mousedown', handleOutside);
    document.addEventListener('touchstart', handleOutside);
    return () => {
      document.removeEventListener('mousedown', handleOutside);
      document.removeEventListener('touchstart', handleOutside);
    };
  }, []);

  const filteredPlans = useMemo(() => {
    const q = normalizeArabicText(searchQuery);
    if (!q) return DIET_PLANS;
    const strippedQ = q.startsWith('ال') && q.length > 2 ? q.slice(2) : q;

    const starts: DietPlan[] = [];
    const contains: DietPlan[] = [];

    for (const plan of DIET_PLANS) {
      const shortNorm = normalizeArabicText(plan.shortName);
      const nameNorm = normalizeArabicText(plan.name);
      const strippedShort = shortNorm.startsWith('ال') ? shortNorm.slice(2) : shortNorm;
      const aliasNorms = plan.aliases.map(normalizeArabicText);

      const isPrefix =
        shortNorm.startsWith(q) ||
        strippedShort.startsWith(strippedQ) ||
        aliasNorms.some((a) => a.startsWith(q) || a.startsWith(strippedQ));

      if (isPrefix) {
        starts.push(plan);
      } else if (
        shortNorm.includes(q) ||
        shortNorm.includes(strippedQ) ||
        nameNorm.includes(q) ||
        aliasNorms.some((a) => a.includes(q) || a.includes(strippedQ))
      ) {
        contains.push(plan);
      }
    }

    return [...starts, ...contains];
  }, [searchQuery]);

  const handleSelectPlan = (plan: DietPlan) => {
    setSelectedPlan(plan);
    setSearchQuery(plan.shortName);
    setIsDropdownOpen(false);
    setCustomError('');
  };

  const handleCustomDiseaseLookup = async (rawName: string) => {
    const clean = rawName.trim();
    if (!clean) return;

    // If it directly matches a built-in plan, select it immediately without API call
    const qNorm = normalizeArabicText(clean);
    const directMatch = DIET_PLANS.find(
      (p) =>
        normalizeArabicText(p.shortName) === qNorm ||
        p.aliases.some((a) => normalizeArabicText(a) === qNorm)
    );
    if (directMatch) {
      handleSelectPlan(directMatch);
      return;
    }

    if (filteredPlans.length === 1 && normalizeArabicText(filteredPlans[0].shortName).includes(qNorm)) {
      handleSelectPlan(filteredPlans[0]);
      return;
    }

    setIsDropdownOpen(false);
    setIsLoadingCustom(true);
    setCustomError('');

    try {
      const res = await fetch(getApiUrl('/api/medical/therapeutic-nutrition'), {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ condition: clean, lang: 'ar' }),
      });

      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const data = await res.json();
      const rawPlan = data.nutritionPlan || data.plan;

      if (!rawPlan) throw new Error('Empty diet response');

      const allowed: string[] = rawPlan.allowedFoods || rawPlan.recommendedFoods || [];
      const forbidden: string[] = rawPlan.forbiddenFoods || rawPlan.foodsToAvoid || [];
      const meals = rawPlan.mealPlan || rawPlan.dailyMealPlan || {};
      const tips: string[] =
        rawPlan.clinicalTips ||
        rawPlan.specificNutrientRestrictions ||
        (rawPlan.goldenDietitianAdvice ? [rawPlan.goldenDietitianAdvice] : []);

      setSelectedPlan({
        id: `custom_${Date.now()}`,
        shortName: clean,
        name: rawPlan.conditionTitleAr || rawPlan.protocolTitle || `الحمية العلاجية لحالة: ${clean}`,
        aliases: [clean],
        description:
          rawPlan.clinicalRationale ||
          `خطة تغذية علاجية مخصصة لحالة (${clean}) تساعد في ضبط الأعراض وتوازن العناصر الغذائية.`,
        allowedFoods: allowed.length > 0 ? allowed : ['الخضراوات الطازجة', 'البروتينات الخالية من الدهون', 'شرب الماء الكافي'],
        forbiddenFoods: forbidden.length > 0 ? forbidden : ['السكريات المكررة', 'الأطعمة المقلية والمصنعة'],
        sampleMealPlan: {
          breakfast: meals.breakfast || 'وجبة إفطار متوازنة غنية بالبروتين والألياف',
          lunch: meals.lunch || 'وجبة غداء معتدلة مع خضار طازجة وبروتين مشوي',
          dinner: meals.dinner || 'وجبة عشاء خفيفة سهلة الهضم',
          snack: meals.snack1 || meals.midMorningSnack || 'فاكهة طازجة أو مكسرات نيئة باعتدال',
        },
        tips: tips.length > 0 ? tips : ['التزم بتوازن الوجبات وشرب الماء والمتابعة مع الطبيب المختص.'],
      });
    } catch {
      setCustomError(`تعذر جلب خطة مخصصة لـ "${clean}" حالياً. يرجى المحاولة مجدداً أو اختيار مرض من القائمة.`);
    } finally {
      setIsLoadingCustom(false);
    }
  };

  const handleCopyPlan = () => {
    const text = `🥗 ${selectedPlan.name}\n\n✅ المسموحة:\n- ${selectedPlan.allowedFoods.join('\n- ')}\n\n❌ الممنوعة:\n- ${selectedPlan.forbiddenFoods.join('\n- ')}\n\n🍽️ نموذج الوجبات:\n🍳 الإفطار: ${selectedPlan.sampleMealPlan.breakfast}\n🥗 الغداء: ${selectedPlan.sampleMealPlan.lunch}\n🥣 العشاء: ${selectedPlan.sampleMealPlan.dinner}\n🍏 السناك: ${selectedPlan.sampleMealPlan.snack}\n\n(منصة جرعة الطبية)`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <div className="space-y-5" id="therapeutic-diet-section">
      {/* Search Box with Dropdown Arrow + Clean Disease Shortcut Buttons ONLY */}
      <div className="bg-slate-900 border border-slate-800 rounded-2xl p-4 sm:p-5 shadow-xl space-y-4">
        {/* Search / Dropdown with Arrow */}
        <div ref={dropdownRef} className="relative z-30">
          <div className="flex gap-2">
            <div className="relative flex-1">
              <Search className="w-4 h-4 text-emerald-400 pointer-events-none absolute right-3.5 top-1/2 -translate-y-1/2" />
              <input
                ref={inputRef}
                type="text"
                aria-label="ابحث أو اختر المرض"
                value={searchQuery}
                placeholder="اكتب اسم المرض أو اختر من السهم..."
                onFocus={() => setIsDropdownOpen(true)}
                onChange={(e) => {
                  setSearchQuery(e.target.value);
                  setIsDropdownOpen(true);
                }}
                onKeyDown={(e) => {
                  if (e.key === 'Enter') {
                    e.preventDefault();
                    handleCustomDiseaseLookup(searchQuery);
                  } else if (e.key === 'Escape') {
                    setIsDropdownOpen(false);
                  }
                }}
                className="w-full bg-slate-950 border border-slate-700 hover:border-emerald-500/60 focus:border-emerald-500 rounded-xl py-3 ps-10 pe-16 text-sm text-white placeholder-slate-400 focus:outline-none transition-colors"
              />

              {searchQuery && (
                <button
                  type="button"
                  aria-label="مسح البحث"
                  onClick={() => {
                    setSearchQuery('');
                    setIsDropdownOpen(true);
                    inputRef.current?.focus();
                  }}
                  className="absolute left-9 top-1/2 -translate-y-1/2 p-1 text-slate-500 hover:text-slate-200 transition-colors cursor-pointer"
                >
                  <X className="w-4 h-4" />
                </button>
              )}

              <button
                type="button"
                aria-label="عرض قائمة الأمراض"
                onClick={() => {
                  setIsDropdownOpen((prev) => !prev);
                  inputRef.current?.focus();
                }}
                className="absolute left-2 top-1/2 -translate-y-1/2 p-1.5 cursor-pointer"
              >
                <ChevronDown
                  className={`w-4 h-4 text-emerald-400 transition-transform duration-150 ${
                    isDropdownOpen ? 'rotate-180' : ''
                  }`}
                />
              </button>
            </div>

            {searchQuery.trim().length >= 2 && (
              <button
                type="button"
                disabled={isLoadingCustom}
                onClick={() => handleCustomDiseaseLookup(searchQuery)}
                className="px-4 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs sm:text-sm font-bold shrink-0 transition-colors cursor-pointer disabled:opacity-50"
              >
                {isLoadingCustom ? <RefreshCw className="w-4 h-4 animate-spin" /> : 'عرض'}
              </button>
            )}
          </div>

          {isDropdownOpen && (
            <div className="absolute left-0 right-0 top-full mt-1.5 bg-slate-950 border border-emerald-500/50 rounded-xl shadow-2xl max-h-64 overflow-y-auto divide-y divide-slate-800/80 z-50">
              {filteredPlans.map((plan) => {
                const isActive = plan.id === selectedPlan.id;
                return (
                  <button
                    key={plan.id}
                    type="button"
                    onMouseDown={(e) => {
                      e.preventDefault();
                      handleSelectPlan(plan);
                    }}
                    className={`w-full text-right px-3.5 py-2.5 text-xs sm:text-sm transition-colors flex items-center justify-between cursor-pointer ${
                      isActive
                        ? 'bg-emerald-950/60 text-emerald-300 font-bold'
                        : 'text-slate-200 hover:bg-slate-900'
                    }`}
                  >
                    <span>{plan.shortName}</span>
                    {isActive && <Check className="w-3.5 h-3.5 text-emerald-400 shrink-0" />}
                  </button>
                );
              })}

              {searchQuery.trim().length >= 2 &&
                !filteredPlans.some(
                  (p) => normalizeArabicText(p.shortName) === normalizeArabicText(searchQuery)
                ) && (
                  <button
                    type="button"
                    onMouseDown={(e) => {
                      e.preventDefault();
                      handleCustomDiseaseLookup(searchQuery);
                    }}
                    className="w-full text-right px-3.5 py-2.5 text-xs sm:text-sm text-teal-300 hover:bg-teal-950/50 font-bold flex items-center gap-2 cursor-pointer"
                  >
                    <Search className="w-3.5 h-3.5 shrink-0" />
                    <span>تجهيز الحمية لـ «{searchQuery.trim()}»</span>
                  </button>
                )}
            </div>
          )}
        </div>

        {/* Clean Disease Name Shortcut Buttons ONLY (No extra categories or descriptions) */}
        <div className="flex flex-wrap gap-2">
          {DIET_PLANS.map((plan) => {
            const isSelected = plan.id === selectedPlan.id;
            return (
              <button
                key={plan.id}
                type="button"
                onClick={() => handleSelectPlan(plan)}
                className={`px-3.5 py-2 rounded-xl text-xs sm:text-sm font-bold border transition-all cursor-pointer ${
                  isSelected
                    ? 'bg-emerald-600 text-white border-emerald-500 shadow-md shadow-emerald-950/50'
                    : 'bg-slate-950 text-slate-300 border-slate-800 hover:border-emerald-500/50 hover:text-white'
                }`}
              >
                {plan.shortName}
              </button>
            );
          })}
        </div>
      </div>

      {customError && (
        <div className="p-3.5 rounded-xl bg-rose-950/40 border border-rose-800/60 text-xs sm:text-sm text-rose-300">
          {customError}
        </div>
      )}

      {/* Selected Diet Plan Details */}
      {isLoadingCustom ? (
        <div className="bg-slate-900 border border-slate-800 rounded-2xl p-10 text-center space-y-3">
          <RefreshCw className="w-8 h-8 mx-auto text-emerald-400 animate-spin" />
          <p className="text-sm font-bold text-white">جاري إعداد الخطة الغذائية العلاجية...</p>
        </div>
      ) : (
        <div className="bg-slate-900 border border-slate-800 rounded-2xl p-5 sm:p-6 shadow-xl space-y-5">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-slate-800">
            <h3 className="text-base sm:text-lg font-bold text-white flex items-center gap-2">
              <HeartPulse className="w-5 h-5 text-emerald-400 shrink-0" />
              <span>{selectedPlan.name}</span>
            </h3>
            <div className="flex items-center gap-2">
              <button
                type="button"
                onClick={() => window.print()}
                className="px-2.5 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs flex items-center gap-1 border border-slate-700 transition-colors cursor-pointer"
              >
                <Share2 className="w-3.5 h-3.5" />
                <span>طباعة</span>
              </button>
              <button
                type="button"
                onClick={handleCopyPlan}
                className="px-2.5 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs flex items-center gap-1 border border-slate-700 transition-colors cursor-pointer"
              >
                {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                <span>{copied ? 'تم النسخ' : 'نسخ'}</span>
              </button>
            </div>
          </div>

          <p className="text-xs sm:text-sm text-slate-300 leading-relaxed bg-slate-950/60 p-3.5 rounded-xl border border-slate-800">
            {selectedPlan.description}
          </p>

          {/* Allowed & Forbidden Foods */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div className="bg-slate-950/80 border border-emerald-500/30 rounded-xl p-4 space-y-3">
              <h4 className="text-xs sm:text-sm font-bold text-emerald-300 flex items-center gap-1.5">
                <Check className="w-4 h-4 text-emerald-400" />
                <span>الأطعمة الموصى بها والمسموحة:</span>
              </h4>
              <ul className="space-y-2">
                {selectedPlan.allowedFoods.map((item, i) => (
                  <li key={i} className="text-xs sm:text-sm text-slate-300 flex items-start gap-2">
                    <span className="text-emerald-400 font-bold">✓</span>
                    <span>{item}</span>
                  </li>
                ))}
              </ul>
            </div>

            <div className="bg-slate-950/80 border border-rose-500/30 rounded-xl p-4 space-y-3">
              <h4 className="text-xs sm:text-sm font-bold text-rose-300 flex items-center gap-1.5">
                <AlertTriangle className="w-4 h-4 text-rose-400" />
                <span>الأطعمة الممنوعة أو الواجب الحذر منها:</span>
              </h4>
              <ul className="space-y-2">
                {selectedPlan.forbiddenFoods.map((item, i) => (
                  <li key={i} className="text-xs sm:text-sm text-slate-300 flex items-start gap-2">
                    <span className="text-rose-400 font-bold">✕</span>
                    <span>{item}</span>
                  </li>
                ))}
              </ul>
            </div>
          </div>

          {/* Sample Meal Plan */}
          <div className="bg-slate-950/80 border border-slate-800 rounded-xl p-4 sm:p-5 space-y-3.5">
            <h4 className="text-xs sm:text-sm font-bold text-teal-300 flex items-center gap-2">
              <Flame className="w-4 h-4 text-amber-400" />
              <span>نموذج يومي مقترح للوجبات:</span>
            </h4>
            <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-3">
              <div className="bg-slate-900 p-3 rounded-lg border border-slate-800">
                <span className="text-[11px] text-slate-400 block font-bold">🍳 الإفطار</span>
                <p className="text-xs text-slate-200 mt-1 leading-relaxed">{selectedPlan.sampleMealPlan.breakfast}</p>
              </div>
              <div className="bg-slate-900 p-3 rounded-lg border border-slate-800">
                <span className="text-[11px] text-slate-400 block font-bold">🥗 الغداء</span>
                <p className="text-xs text-slate-200 mt-1 leading-relaxed">{selectedPlan.sampleMealPlan.lunch}</p>
              </div>
              <div className="bg-slate-900 p-3 rounded-lg border border-slate-800">
                <span className="text-[11px] text-slate-400 block font-bold">🥣 العشاء</span>
                <p className="text-xs text-slate-200 mt-1 leading-relaxed">{selectedPlan.sampleMealPlan.dinner}</p>
              </div>
              <div className="bg-slate-900 p-3 rounded-lg border border-slate-800">
                <span className="text-[11px] text-slate-400 block font-bold">🍏 سناك خفيف</span>
                <p className="text-xs text-slate-200 mt-1 leading-relaxed">{selectedPlan.sampleMealPlan.snack}</p>
              </div>
            </div>
          </div>

          {/* Clinical Tips */}
          <div className="bg-slate-800/40 border border-slate-700/60 rounded-xl p-4 space-y-2">
            <h4 className="text-xs sm:text-sm font-bold text-amber-300 flex items-center gap-1.5">
              <ShieldCheck className="w-4 h-4" />
              <span>نصائح إكلينيكية هامة لنجاح الحمية:</span>
            </h4>
            <ul className="space-y-1.5">
              {selectedPlan.tips.map((t, idx) => (
                <li key={idx} className="text-xs sm:text-sm text-slate-300 flex items-start gap-2">
                  <span className="text-amber-400">•</span>
                  <span>{t}</span>
                </li>
              ))}
            </ul>
          </div>
        </div>
      )}
    </div>
  );
};
